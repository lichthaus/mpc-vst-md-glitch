def control_box(cx, row, kind):
    if kind == "knob":
        return cx - KNOB // 2, ROW_Y[row] + 16, KNOB, KNOB
    return cx - SWITCH // 2, ROW_Y[row] + 16 + (KNOB - SWITCH) // 2, SWITCH, SWITCH


