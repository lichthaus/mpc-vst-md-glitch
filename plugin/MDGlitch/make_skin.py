def char_glyph(code, ss):
    """One character cell at ss x size, white on black (used as a mask)."""
    w, h = CELL_W * ss, CELL_H * ss
    g = Image.new("L", (w, h), 0)
    d = ImageDraw.Draw(g)
    if code == 0x10:                                    # play
        d.polygon([(w * 0.22, h * 0.26), (w * 0.22, h * 0.74), (w * 0.82, h * 0.5)], fill=255)
    elif code == 0x11:                                  # hold (pause bars)
        d.rectangle([w * 0.2, h * 0.27, w * 0.42, h * 0.73], fill=255)
        d.rectangle([w * 0.58, h * 0.27, w * 0.8, h * 0.73], fill=255)
    elif code == 0x12:                                  # stop
        d.rectangle([w * 0.2, h * 0.3, w * 0.8, h * 0.7], fill=255)
    elif 0x21 <= code < 0x7F:
        f = font(MENLO, 36 * ss, index=1)
        ch = chr(code)
        b = d.textbbox((0, 0), ch, font=f)
        d.text(((w - (b[2] - b[0])) / 2 - b[0], (h - 36 * ss) / 2 - 2 * ss), ch, font=f, fill=255)
    return g


def char_strip(path):
    ss = 3
    strip = Image.new("RGB", (CELL_W, CELL_H * 256), WINDOW)
    # a faint 5 x 8 dot grid behind every cell, like an unlit display
    grid = Image.new("RGB", (CELL_W, CELL_H), WINDOW)
    gd = ImageDraw.Draw(grid)
    for y in range(8):
        for x in range(5):
            cx, cy = 4 + x * 5, 4 + y * 5.2
            gd.rectangle([cx, cy, cx + 2, cy + 2], fill=VFD_OFF)
    for code in range(256):
        cell = grid.copy()
        g = char_glyph(code, ss).resize((CELL_W, CELL_H), Image.LANCZOS)
        lit = Image.new("RGB", (CELL_W, CELL_H), VFD_ON)
        cell.paste(lit, (0, 0), g)
        cell = glow(cell, VFD_ON, radius=2, strength=0.35) if g.getbbox() else cell
        strip.paste(cell, (0, code * CELL_H))
    strip.save(path, optimize=True)


def disc_strip(path):
    ss = 3
    w, h = DISC[2], DISC[3]
    strip = Image.new("RGB", (w, h * DISC_FRAMES), WINDOW)
    for f in range(DISC_FRAMES):
        big = Image.new("RGB", (w * ss, h * ss), WINDOW)
        d = ImageDraw.Draw(big)
        c, R = w * ss / 2, w * ss * 0.47
        d.ellipse([c - R, c - R, c + R, c + R], fill=(0x1E, 0x20, 0x26), outline=(0x3C, 0x3F, 0x48), width=2 * ss)
        for k in range(14):                             # data rings
            r = R * (0.42 + 0.04 * k)
            shade = 0x24 + (k % 3) * 5
            d.ellipse([c - r, c - r, c + r, c + r], outline=(shade, shade + 2, shade + 8), width=ss)
        # a fixed sheen (does not turn) and the turning parts: hub with three slots and a label tick
        d.pieslice([c - R * 0.98, c - R * 0.98, c + R * 0.98, c + R * 0.98], 200, 235, fill=(0x25, 0x27, 0x2E))
        a0 = 360.0 * f / DISC_FRAMES
        hub = R * 0.3
        d.ellipse([c - hub, c - hub, c + hub, c + hub], fill=(0x8C, 0x90, 0x98), outline=(0x50, 0x53, 0x5A), width=ss)
        for k in range(3):
            a = math.radians(a0 + k * 120)
            x, y = c + math.cos(a) * hub * 0.6, c + math.sin(a) * hub * 0.6
            r = hub * 0.18
            d.ellipse([x - r, y - r, x + r, y + r], fill=(0x30, 0x32, 0x38))
        d.ellipse([c - hub * 0.22, c - hub * 0.22, c + hub * 0.22, c + hub * 0.22], fill=(0x20, 0x22, 0x26))
        a = math.radians(a0 + 60)
        d.line([(c + math.cos(a) * R * 0.5, c + math.sin(a) * R * 0.5), (c + math.cos(a) * R * 0.9, c + math.sin(a) * R * 0.9)],
               fill=VFD_ON, width=3 * ss)
        strip.paste(big.resize((w, h), Image.LANCZOS), (0, f * h))
    strip.save(path, optimize=True)


def segment_strip(path, w, h, segments, frames, colour_of):
    strip = Image.new("RGB", (w, h * frames), WINDOW)
    d = ImageDraw.Draw(strip)
    gap = 3
    sw = (w - gap * (segments - 1)) / segments
    for f in range(frames):
        for k in range(segments):
            on, off = colour_of(k)
            x = k * (sw + gap)
            d.rectangle([x, f * h + 1, x + sw - 1, f * h + h - 2], fill=on if k < f else off)
    strip.save(path, optimize=True)


def meter_colour(k):
    if k >= 14:
        return RED, (0x3A, 0x10, 0x0E)
    if k >= 10:
        return AMBER, (0x3A, 0x28, 0x0A)
    return VFD_ON, VFD_OFF


def knob_strip(path):
    ss = 4
    s = KNOB * ss
    strip = Image.new("RGBA", (KNOB, KNOB * KNOB_FRAMES), (0, 0, 0, 0))
    for i in range(KNOB_FRAMES):
        big = Image.new("RGBA", (s, s), (0, 0, 0, 0))
        d = ImageDraw.Draw(big)
        c = s / 2
        a1 = 120 + 300 * i / (KNOB_FRAMES - 1)
        d.arc([s * 0.04, s * 0.04, s * 0.96, s * 0.96], 120, 420, fill=(0x30, 0x32, 0x37, 255), width=ss * 4)
        if i:
            d.arc([s * 0.04, s * 0.04, s * 0.96, s * 0.96], 120, a1, fill=VFD_ON + (255,), width=ss * 4)
        r = s * 0.36
        d.ellipse([c - r, c - r, c + r, c + r], fill=(0x2A, 0x2B, 0x30, 255), outline=(0x48, 0x4A, 0x50, 255), width=ss * 2)
        r2 = r * 0.78
        d.ellipse([c - r2, c - r2, c + r2, c + r2], fill=(0x36, 0x38, 0x3E, 255))
        a = math.radians(a1)
        d.line([(c + math.cos(a) * r * 0.25, c + math.sin(a) * r * 0.25), (c + math.cos(a) * r * 0.92, c + math.sin(a) * r * 0.92)],
               fill=(0xF4, 0xF4, 0xF4, 255), width=ss * 3)
        strip.paste(big.resize((KNOB, KNOB), Image.LANCZOS), (0, i * KNOB))
    strip.save(path, optimize=True)


