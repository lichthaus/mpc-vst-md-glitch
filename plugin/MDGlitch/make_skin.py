def font(path, size, index=0):
    try:
        return ImageFont.truetype(path, size, index=index)
    except OSError:
        return ImageFont.load_default()


def centred(d, box, text, f, fill):
    x0, y0, x1, y1 = box
    b = d.textbbox((0, 0), text, font=f)
    d.text(((x0 + x1 - (b[2] - b[0])) / 2 - b[0], (y0 + y1 - (b[3] - b[1])) / 2 - b[1]), text, font=f, fill=fill)


def glow(img, colour, radius=3, strength=0.55):
    """Adds a soft halo of the lit pixels, like a fluorescent display."""
    mask = img.convert("L")
    halo = Image.new("RGB", img.size, colour)
    blur = mask.filter(ImageFilter.GaussianBlur(radius)).point(lambda v: int(v * strength))
    base = img.copy()
    base.paste(halo, (0, 0), blur)
    base.paste(img, (0, 0), mask)
    return base


