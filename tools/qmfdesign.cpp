// Start: Kaiser-windowed sinc at a quarter of the sample rate. Then plain gradient descent on
//   cost = sum_w (A(w)^2 + A(pi-w)^2 - 1)^2  +  lambda * sum_{w >= ws} A(w)^2
// where A is the real amplitude response of the symmetric filter. The first term is the
// QMF reconstruction ripple (aliasing cancels by structure), the second the stopband energy
// (aliasing between bands once they are quantised). Writes core/qmf_coefs.h.
#include <cmath>
#include <cstdio>
#include <vector>

constexpr int N = 32, H = N / 2, K = 1024;
static double amp(const double* h, double w) {  // A(w) = 2 sum h[n] cos(w (N-1)/2 - n))
    double a = 0;
    for (int n = 0; n < H; n++) a += 2 * h[n] * std::cos(w * ((N - 1) / 2.0 - n));
    return a;
}
static double bessel0(double x) {
    double s = 1, t = 1;
    for (int k = 1; k < 30; k++) { t *= (x / (2 * k)) * (x / (2 * k)); s += t; }
    return s;
}
static double cost(const double* h, double lambda, double ws, double* ripple, double* stop) {
    double c = 0, rmax = 0, smax = 0;
    for (int k = 0; k <= K; k++) {
        const double w = M_PI * k / K;
        const double a = amp(h, w), b = amp(h, M_PI - w);
        const double r = a * a + b * b - 1;
        c += r * r;
        rmax = std::fmax(rmax, std::fabs(r));
        if (w >= ws) { c += lambda * a * a; smax = std::fmax(smax, std::fabs(a)); }
    }
    if (ripple) *ripple = rmax;
    if (stop) *stop = smax;
    return c;
}
int main() {
    double h[H];
    const double beta = 6.0;
    for (int n = 0; n < H; n++) {
        const double m = n - (N - 1) / 2.0;
        const double sinc = std::sin(M_PI * 0.5 * m) / (M_PI * m);
        const double r = 2.0 * n / (N - 1) - 1.0;
        h[n] = sinc * bessel0(beta * std::sqrt(1 - r * r)) / bessel0(beta);
    }
    double s = 0;
    for (int n = 0; n < H; n++) s += 2 * h[n];
    for (int n = 0; n < H; n++) h[n] /= s;
    const double lambda = 0.2, ws = M_PI * 0.62;
    double step = 1e-4, c = cost(h, lambda, ws, nullptr, nullptr);
    for (int it = 0; it < 20000; it++) {
        double g[H];
        for (int n = 0; n < H; n++) {
            const double e = 1e-7, keep = h[n];
            h[n] = keep + e; const double cp = cost(h, lambda, ws, nullptr, nullptr);
            h[n] = keep - e; const double cm = cost(h, lambda, ws, nullptr, nullptr);
            h[n] = keep;
            g[n] = (cp - cm) / (2 * e);
        }
        double t[H];
        for (;;) {
            for (int n = 0; n < H; n++) t[n] = h[n] - step * g[n];
            const double ct = cost(t, lambda, ws, nullptr, nullptr);
            if (ct < c) { for (int n = 0; n < H; n++) h[n] = t[n]; c = ct; step *= 1.2; break; }
            step *= 0.5;
            if (step < 1e-14) break;
        }
        if (step < 1e-14) break;
    }
    double ripple, stop;
    cost(h, lambda, ws, &ripple, &stop);
    std::fprintf(stderr, "ripple %.5f dB, stopband (>= %.2f fs) %.1f dB\n", 10 * std::log10(1 + ripple),
                 ws / (2 * M_PI), 20 * std::log10(stop));
    FILE* f = std::fopen("core/qmf_coefs.h", "w");
    std::fprintf(f, "// qmf_coefs.h - generated by tools/qmfdesign.cpp; do not edit.\n");
    std::fprintf(f, "// SPDX-License-Identifier: MIT\n");
    std::fprintf(f, "// 32-tap linear-phase QMF prototype, first half (h[31-n] = h[n]).\n");
    std::fprintf(f, "// Reconstruction ripple %.5f dB, stopband from %.2f fs: %.1f dB.\n", 10 * std::log10(1 + ripple),
                 ws / (2 * M_PI), 20 * std::log10(stop));
    std::fprintf(f, "#pragma once\nnamespace md {\nconstexpr int kQmfTaps = %d;\nconstexpr float kQmfHalf[%d] = {\n", N, H);
    for (int n = 0; n < H; n++) std::fprintf(f, "    %.9ef,\n", h[n]);
    std::fprintf(f, "};\n}  // namespace md\n");
    std::fclose(f);
}
